const assert = require('node:assert/strict');
const data = require('../src/main.js');
const host = require('./test-host.cjs');
const { fixture, open, click, openedModals } = host;
const dir = 'papers/test';
const indexPath = `${dir}/【索引】test.md`;
const paperPath = (slug) => `${dir}/【2026】${slug}/【2026】${slug}.md`;
const note = (slug) => `---\ntitle: '${slug}'\nyear: 2026\nreading: 未读\nimportance: 1\ntable_summary: '简介${slug}'\ntags: [test]\n---\n## 整体综述\n综述${slug}\n\n### 关键机制\n机制说明\n\n## 方法\n不可覆盖的方法${slug}\n\n## 我的批注与 Open debates\n个人记录${slug}\n`;
(async () => {
  const { plugin, contents, fail, app } = fixture();
  let modal = await open(plugin);
  assert.equal(modal.file.path, paperPath('a'));
  assert.equal(data.parseFrontmatter(contents.get(modal.file.path)).reading, '未读', 'Browsing must not mark a paper read');
  assert.equal(modal.sections.overview.content.sourcePath, modal.file.path, 'Markdown links must resolve from the paper');
  assert.equal(modal.reader.animations.length, 1);
  plugin.openBrowse(); assert.equal(plugin.browseModal, modal, 'Only one modal should open');
  await click(modal, '再刷一篇'); assert.equal(modal.file.path, paperPath('b'));
  await click(modal, '已读');
  assert.equal(modal.reader.animations.length, 2, 'Editing a status must not repeat the paper transition');
  assert.equal(data.parseFrontmatter(contents.get(paperPath('b'))).reading, '已读');
  await click(modal, '再刷一篇'); assert.equal(modal.file.path, paperPath('a'));
  await click(modal, '编辑内容');
  modal.sections.overview.input.value += '我的批注\n';
  modal.sections.notes.input.value = "A practitioner's summary";
  modal.updateDirty();
  await click(modal, '再刷一篇');
  const saved = contents.get(paperPath('a'));
  assert.ok(saved.includes('我的批注'));
  assert.ok(data.browseNoteSnapshot(saved).notes.includes("A practitioner's summary"));
  assert.equal(data.parseFrontmatter(saved).summary, '简介a');
  assert.ok(saved.includes('不可覆盖的方法a'));
  assert.ok(saved.includes('## 我的批注与 Open debates'));
  assert.ok(contents.get(indexPath).includes('旧表'), 'Section edits must not rewrite the direction index');
  assert.ok(contents.get(indexPath).includes('介绍应保留'));
  await click(modal, '已读');
  await click(modal, '未设置');
  await click(modal, '再刷一篇');
  assert.equal(modal.file.path, paperPath('a'), 'Only the unrated paper should be selected now');
  assert.ok(modal.poolEl.textContent.includes('优先未设置重要度'));
  await click(modal, '3');
  await click(modal, '再刷一篇');
  assert.ok(modal.poolEl.textContent.includes('随机回顾'));

  // Save failures and concurrent body changes must keep the modal and input intact.
  await click(modal, '编辑内容');
  modal.sections.overview.input.value += '未保存批注'; modal.updateDirty();
  const current = modal.file.path;
  fail(); await modal.close();
  assert.equal(modal.nativeClosed, undefined);
  assert.equal(modal.isDirty(), true);
  contents.set(current, contents.get(current).replace('机制说明', '机制说明外部批注'));
  await click(modal, '再刷一篇');
  assert.equal(modal.file.path, current);
  assert.ok(modal.sections.overview.input.value.includes('未保存批注'));
  assert.ok(contents.get(current).includes('外部批注'));
  assert.ok(modal.status.textContent.includes('整体综述已在其他地方修改'));
  await click(modal, '重新载入');
  assert.ok(modal.sections.overview.input.value.includes('外部批注'));
  assert.equal(modal.isDirty(), false);
  modal.sections.notes.input.value = '关闭前保存'; modal.updateDirty();
  await modal.close();
  assert.equal(modal.nativeClosed, true);
  assert.equal(plugin.browseModal, null);
  assert.equal(plugin.children.size, 0, 'Markdown renderer components must be unloaded');
  assert.ok(data.browseNoteSnapshot(contents.get(current)).notes.includes('关闭前保存'));

  modal = await open(plugin);
  await click(modal, '打开笔记');
  assert.ok(app.openedFile); assert.equal(modal.nativeClosed, true);
  const windows = fixture();
  host.setReducedMotion(true);
  const windowsNote = note('a').replace("'简介a'", "' 简介a '").replace(/\n/g, '\r\n');
  windows.contents.set(paperPath('a'), windowsNote);
  modal = await open(windows.plugin);
  assert.equal(modal.reader.animations.length, 0, 'Respect reduced motion');
  assert.equal(modal.isDirty(), false, 'Textarea newline normalization must not mark an untouched note dirty');
  await modal.close();
  assert.equal(windows.contents.get(paperPath('a')), windowsNote, 'Simply browsing must preserve CRLF and whitespace byte for byte');
  host.setReducedMotion(false);
  const deleted = fixture();
  modal = await open(deleted.plugin);
  await click(modal, '编辑内容');
  modal.sections.overview.input.value += '本地草稿'; modal.updateDirty();
  deleted.contents.delete(modal.file.path);
  await modal.close();
  assert.equal(modal.nativeClosed, undefined, 'A failed save must leave the draft available to copy');
  await click(modal, '放弃修改');
  await modal.close();
  assert.equal(modal.nativeClosed, true, 'The user must be able to discard a draft even after external deletion');
  const missing = fixture();
  missing.contents.set(paperPath('a'), note('a').split('## 我的批注与 Open debates')[0] + '## 路径\n保留链接\n');
  modal = await open(missing.plugin);
  assert.equal(modal.sections.notes.input.value, '');
  assert.ok(modal.sections.notes.content.children[0].textContent.includes('还没写下想法'));
  await click(modal, '编辑内容');
  modal.sections.notes.input.value = '补充新 Notes'; modal.updateDirty();
  const old = missing.contents.get(paperPath('a'));
  missing.contents.set(paperPath('a'), old.replace('不可覆盖的方法a', '外部修改的方法a'));
  await click(modal, '保存并预览');
  assert.ok(missing.contents.get(paperPath('a')).includes('外部修改的方法a'));
  assert.ok(missing.contents.get(paperPath('a')).includes('## 阅读随记'));
  assert.ok(data.browseNoteSnapshot(missing.contents.get(paperPath('a'))).notes.includes('补充新 Notes'));
  await modal.close();
  const empty = fixture(true);
  modal = await open(empty.plugin);
  assert.equal(modal.file, null);
  assert.equal(modal.openButton.disabled, true);
  await click(modal, '再刷一篇');
  await modal.close();
  assert.equal(empty.plugin.children.size, 0);
  const homeFixture = fixture();
  await homeFixture.app.vault.create('【索引】研究总览.md', '---\ntitle: 研究总览\n---\n');
  await homeFixture.plugin.onload();
  assert.equal(homeFixture.plugin.ribbons.length, 1, 'A single sidebar entry should lead to Home');
  assert.equal(homeFixture.plugin.ribbons[0].icon, 'house');
  const home = await homeFixture.plugin.activateHome();
  assert.equal(home.getViewType(), 'pinakes-home-view');
  assert.equal(homeFixture.leaves.length, 1, 'Opening Home must not create a graph leaf');
  const homeElement = home.contentEl;
  const viewCount = host.getItemViewConstructions();
  const resourceRecommendation = home.featuredPath;
  await click(home, '检查资源');
  const resourceModal = openedModals.at(-1);
  assert.equal(resourceModal.titleEl.textContent, '检查资源');
  assert.equal(host.getItemViewConstructions(), viewCount, 'Resource checks must never instantiate another ItemView on the Home leaf');
  resourceModal.close(); // Same Modal.close path as the native X and Escape.
  assert.equal(resourceModal.nativeClosed, true);
  assert.equal(home.contentEl, homeElement);
  assert.equal(home.closed, false);
  assert.equal(home.featuredPath, resourceRecommendation);
  assert.equal(homeFixture.app.workspace.activeLeaf.view, home);
  await click(home, '检查资源');
  const secondResourceModal = openedModals.at(-1);
  await click(secondResourceModal, '关闭');
  assert.equal(secondResourceModal.nativeClosed, true);
  assert.equal(host.getItemViewConstructions(), viewCount, 'Repeated checks must leave only the Home view');
  const firstRecommendation = home.featuredPath;
  await homeFixture.plugin.activateHome();
  assert.notEqual(home.featuredPath, firstRecommendation, 'Re-entering Home refreshes its recommendation');
  const featured = home.featuredPath;
  await click(home, '读这一篇');
  modal = homeFixture.plugin.browseModal; await modal.opened;
  assert.equal(modal.file.path, featured, 'The featured paper and the opened reader must agree');
  await click(modal, '已读');
  assert.equal(home.featuredPath, featured, 'Metadata refresh should keep the displayed Home paper stable');
  await modal.close();
  await homeFixture.plugin.activateHome();
  assert.notEqual(home.featuredPath, featured);
  const queuePath = '_dashboards/reading-queue.md';
  await homeFixture.app.vault.create(queuePath, 'queue');
  await click(home, '阅读队列'); assert.equal(homeFixture.app.workspace.activeLeaf.view.mode, 'queue');
  const filesBefore = homeFixture.contents.size;
  await home.libraryAction((library) => library.addPaperFromPdf({ file: null, dirName: 'test', year: '2026', slug: 'home-added',
    title: 'Added from home', tags: ['test'], authors: [], summary: 'home import', abstract: '' }));
  assert.equal(homeFixture.app.vault.getMarkdownFiles().filter(f => f.path.includes('【2026】home-added/')).length, 1);
  assert.ok(homeFixture.contents.get(indexPath).includes('Added from home'));
  assert.equal(homeFixture.leaves.filter(l => l.type === 'pinakes-explorer-view').length, 0, 'Home import must not open the graph');
  home.onClose(); assert.equal(homeFixture.plugin.children.size, 0);
  const emptyHome = fixture(true); await emptyHome.plugin.onload();
  const freshHome = await emptyHome.plugin.activateHome();
  assert.equal(freshHome.featuredPath, null);
  assert.equal(emptyHome.contents.size, 0, 'Viewing an empty Home must not create notes');
  await freshHome.libraryAction((library) => library.addPaperFromPdf({ file: null, dirName: '_unfiled', year: '2026', slug: 'first',
    title: 'First paper', tags: [], authors: [], summary: '', abstract: '' }));
  assert.ok([...emptyHome.contents.keys()].some((p) => p.includes('【2026】first.md')), 'Home import must bootstrap an empty vault');
  assert.equal(emptyHome.leaves.length, 1);
  freshHome.onClose();
  console.log('Browse modal verified: section extraction and edits, preserved hidden content, metadata, conflicts, failed saves, close, empty vault, reduced motion and renderer cleanup.');
  console.log('Home verified: single sidebar entry, graph deferred, recommendation reset, exact paper reader, metadata refresh, queue, import and empty vault bootstrap.');
})().catch((error) => { console.error(error); process.exitCode = 1; });
